const Attendance = () => {
  const rows = 7; // Number of rows in the grid
  const cols = 5; // Number of columns in the grid

  // State to store grids for four keys
  const [grids, setGrids] = useState([
    Array.from({ length: rows }, () => Array(cols).fill(0)),
    Array.from({ length: rows }, () => Array(cols).fill(0)),
    Array.from({ length: rows }, () => Array(cols).fill(0)),
    Array.from({ length: rows }, () => Array(cols).fill(0)),
  ]);

  // State to track keys pressed
  const [activeKeys, setActiveKeys] = useState([null, null, null, null]);

  const handleKeyDown = (event) => {
    const letter = event.key.toUpperCase();
    console.log(letter, "letter pressed");
    let indexe = 0;
    if (LETTERS[letter]) {
      setActiveKeys((prevKeys) => {
        let nextKeys = [...prevKeys];
        const emptyIndex = nextKeys.findIndex((key) => key === null);
        if (emptyIndex !== -1) {
          nextKeys[emptyIndex] = letter;
          indexe = emptyIndex;
        }
        return nextKeys;
      });

      setGrids((prevGrids) => {
        let nextGrids = [...prevGrids];
        activeKeys.forEach((key, index) => {
          if (indexe === index) {
            nextGrids[index] = LETTERS[letter];
          }
        });
        return nextGrids;
      });
    }
  };

  const handleKeyUp = (event) => {
    const letter = event.key.toUpperCase();
    setActiveKeys((prevKeys) =>
      prevKeys.map((key) => (key === letter ? null : key))
    );

    setGrids((prevGrids) =>
      prevGrids.map((grid, index) =>
        activeKeys[index] === letter
          ? Array.from({ length: rows }, () => Array(cols).fill(0))
          : grid
      )
    );
  };

  useEffect(() => {
    window.addEventListener("keydown", handleKeyDown);
    window.addEventListener("keyup", handleKeyUp);
    return () => {
      window.removeEventListener("keydown", handleKeyDown);
      window.removeEventListener("keyup", handleKeyUp);
    };
  }, [activeKeys]);

  return (
    <div className="main">
      {grids.map((grid, gridIndex) => (
        <div className="grid" key={`grid-${gridIndex}`}>
          {grid.map((row, rowIndex) =>
            row.map((cell, colIndex) => (
              <div
                key={`${gridIndex}-${rowIndex}-${colIndex}`}
                className="block"
                style={{
                  backgroundColor: cell ? "green" : "rgb(242, 242, 242)",
                }}
              ></div>
            ))
          )}
        </div>
      ))}
    </div>
  );
};

export default Attendance;
